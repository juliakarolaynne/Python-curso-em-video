metro = float(input('Digite a quantidade de metros: '))
quilometro = metro / 1000
hectometro = metro / 100
decametro = metro / 10
decimetro = metro * 10
centimetro = metro * 100
milimetro = metro * 1000

print('A quantidade de {} metros equivale a {} quilômetros, {} hectômetro, {} decâmetro, {} decimetros, {} centímetros e {} milímetros'.format(metro, quilometro, hectometro, decametro, decimetro, centimetro, milimetro))